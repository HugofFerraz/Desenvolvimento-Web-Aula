let n1 = prompt("Digite o primeiro valor: ");
let n2 = prompt("Digite o segundo valor: ");

let r1 = parseInt(n1) + parseInt(n2);
let r2 = parseInt(n1) - parseInt(n2);
let r3 = parseInt(n1) * parseInt(n2);
let r4 = parseInt(n1) / parseInt(n2);

document.write("Resultado soma: " + r1 + "<br>");
document.write("Resultado subtração: " + r2  + "<br>");
document.write("Resultado multiplicação: " + r3  + "<br>");
document.write("Resultado divisão: " + r4  + "<br>");